// 播報詞庫(固定句,全部預烤 mp3)——★人聲鐵律:預烤 mp3,不用 Web Speech;短句斷流雷:句子完整收尾。
export function voiceKey(text) {
  const s = String(text).replace(/\s+/g, "");
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = (h * 0x01000193) >>> 0;
  }
  return h.toString(36);
}

